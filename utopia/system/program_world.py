"""A small recurrent science world whose complete numeric rollout is differentiable.

Institution rules execute the mechanism AST interpreter. The world includes
resource allocation, production, dissemination, learning and recurrent state.
Rule choice, node/edge presence, delay and schedule have explicit relaxations;
projected hard systems are evaluated by the same transition equations.
"""
from __future__ import annotations

from copy import deepcopy
from dataclasses import replace
import itertools
import math
from typing import Any, Mapping

import torch

from utopia.optimization.generative_system import (
    EFFECTS, synthesize_program, validate_generative_system,
)
from utopia.optimization.loss import loss_spec_sha256, validate_loss_spec
from utopia.system import ConnectionSpec, ChannelKind, ScheduleSpec, SystemSpec
from utopia.system.programs import execute_program, digest, validate_program

DTYPE = torch.float64
WORLD_SCHEMA = "scienceutopia.program-world.v1"
METRICS = {"production", "knowledge", "novelty", "resource_dispersion", "burden"}


def initial_world(seed: int, population: int = 6) -> dict[str, Any]:
    if isinstance(population, bool) or not isinstance(population, int) or not 2 <= population <= 10:
        raise ValueError("miniature population must be in [2,10]")
    generator = torch.Generator().manual_seed(seed)
    return {
        "schema": WORLD_SCHEMA, "seed": seed, "population": population,
        "quality": (0.2 + 0.5 * torch.rand(population, generator=generator, dtype=DTYPE)).tolist(),
        "novelty": (0.1 + 0.8 * torch.rand(population, generator=generator, dtype=DTYPE)).tolist(),
        "resources": (0.2 + 0.6 * torch.rand(population, generator=generator, dtype=DTYPE)).tolist(),
        "knowledge": [0.1] * population,
        "source": {"kind": "seeded-numeric-world", "seed": seed},
    }


def validate_world(world: Mapping[str, Any]) -> None:
    if world.get("schema") != WORLD_SCHEMA:
        raise ValueError("unsupported program world")
    size = world.get("population")
    if isinstance(size, bool) or not isinstance(size, int) or not 2 <= size <= 10:
        raise ValueError("world population must be in [2,10]")
    for name in ("quality", "novelty", "resources", "knowledge"):
        values = world.get(name)
        if not isinstance(values, list) or len(values) != size:
            raise ValueError(f"world {name} shape mismatch")
        if any(isinstance(value, bool) or not isinstance(value, (int, float))
               or not math.isfinite(value) or not 0 <= value <= 1 for value in values):
            raise ValueError(f"world {name} values must be in [0,1]")


class RelaxedProgramSystem(torch.nn.Module):
    """A mutable design, not a fitted prediction of the loss surface.

    Rule alternatives are recursively generated ASTs. Continuous parameters,
    operator mixtures, graph gates and process mixtures are differentiable.
    New ASTs/nodes can be generated by the black-box outer search between
    gradient episodes. A gradient episode itself uses a finite supergraph.
    """

    def __init__(
        self, system: SystemSpec, *, alternatives: int = 3, seed: int = 0,
        freedom: str = "process",
    ) -> None:
        super().__init__()
        validate_generative_system(system)
        if alternatives < 1 or alternatives > 4:
            raise ValueError("alternatives must be in [1,4]")
        if freedom not in {"parameters", "rules", "graph", "process"}:
            raise ValueError("unknown design freedom")
        self.system = system
        self.freedom = freedom
        self.names = [node.mechanism_id for node in system.mechanisms]
        self.bank: dict[str, list[dict[str, Any]]] = {}
        self.parameters_raw = torch.nn.ParameterDict()
        self.parameter_keys: dict[tuple[str, int, str], str] = {}
        self.node_logits = torch.nn.ParameterDict()
        self.rule_logits = torch.nn.ParameterDict()
        self.edge_logits = torch.nn.ParameterDict()
        self.delay_logits = torch.nn.ParameterDict()
        self.edge_keys: dict[tuple[str, str], str] = {}
        for index, node in enumerate(system.mechanisms):
            base = deepcopy(node.parameters["program"])
            # Alternative programs share the numeric-world feature protocol,
            # while keeping their own independently recurrent internal state.
            self.bank[node.mechanism_id] = [base] + [
                synthesize_program(seed=seed + 1009 * index + alternative)
                for alternative in range(1, alternatives)
            ]
            for alternative, program in enumerate(self.bank[node.mechanism_id]):
                for name, config in program["parameters"].items():
                    normalized = ((config["initial"] - config["minimum"])
                                  / (config["maximum"] - config["minimum"]))
                    normalized = min(max(normalized, 1e-6), 1 - 1e-6)
                    key = f"p{len(self.parameter_keys)}"
                    self.parameter_keys[node.mechanism_id, alternative, name] = key
                    self.parameters_raw[key] = torch.nn.Parameter(torch.tensor(
                        math.log(normalized / (1 - normalized)), dtype=DTYPE,
                    ))
            self.node_logits[node.mechanism_id] = torch.nn.Parameter(torch.tensor(2.0, dtype=DTYPE))
            logits = torch.zeros(alternatives, dtype=DTYPE)
            logits[0] = 1.0
            self.rule_logits[node.mechanism_id] = torch.nn.Parameter(logits)
        actual = {(edge.source_mechanism, edge.target_mechanism): edge
                  for edge in system.connections}
        for source, target in itertools.permutations(self.names, 2):
            key = f"e{len(self.edge_keys)}"
            self.edge_keys[source, target] = key
            edge = actual.get((source, target))
            self.edge_logits[key] = torch.nn.Parameter(torch.tensor(
                2.0 if edge is not None else -2.0, dtype=DTYPE,
            ))
            self.delay_logits[key] = torch.nn.Parameter(torch.tensor(
                2.0 if edge is not None and edge.latency == 1 else -2.0, dtype=DTYPE,
            ))
        order = tuple(item.mechanism_id for item in sorted(
            system.schedules, key=lambda item: (item.phase, item.mechanism_id),
        ))
        schedules = [order, tuple(reversed(order))]
        if len(order) >= 2:
            schedules.append((order[1], order[0], *order[2:]))
        self.orders = list(dict.fromkeys(schedules))
        schedule = torch.zeros(len(self.orders), dtype=DTYPE)
        schedule[0] = 1.0
        self.schedule_logits = torch.nn.Parameter(schedule)
        for name, parameter in self.named_parameters():
            if name.startswith("parameters_raw."):
                active = True
            elif name.startswith("rule_logits."):
                active = freedom in {"rules", "graph", "process"}
            elif name.startswith(("node_logits.", "edge_logits.")):
                active = freedom in {"graph", "process"}
            else:
                active = freedom == "process"
            parameter.requires_grad_(active)

    def parameter_values(self, name: str, alternative: int) -> dict[str, torch.Tensor]:
        program = self.bank[name][alternative]
        return {
            key: config["minimum"] + (
                config["maximum"] - config["minimum"]
            ) * self.parameters_raw[self.parameter_keys[name, alternative, key]].sigmoid()
            for key, config in program["parameters"].items()
        }

    def project(self) -> tuple[SystemSpec, dict[str, Any]]:
        """Choose actual programs, nodes, edges, delays and a total schedule."""
        nodes = []
        decisions: dict[str, Any] = {"nodes": {}, "edges": [], "schedule": None}
        for node in self.system.mechanisms:
            name = node.mechanism_id
            present = (float(self.node_logits[name].detach()) >= 0
                       if self.freedom in {"graph", "process"} else True)
            choice = (int(self.rule_logits[name].detach().argmax())
                      if self.freedom != "parameters" else 0)
            decisions["nodes"][name] = {"present": present, "rule_index": choice}
            if not present:
                continue
            program = deepcopy(self.bank[name][choice])
            for key, value in self.parameter_values(name, choice).items():
                program["parameters"][key]["initial"] = float(value.detach())
            validate_program(program)
            parameters = {**node.parameters, "program": program}
            nodes.append(replace(node, parameters=parameters))
        active = {node.mechanism_id for node in nodes}
        actual = {(edge.source_mechanism, edge.target_mechanism): edge
                  for edge in self.system.connections}
        edges = []
        for pair, key in self.edge_keys.items():
            present = (float(self.edge_logits[key].detach()) >= 0
                       if self.freedom in {"graph", "process"} else pair in actual)
            delay = (int(float(self.delay_logits[key].detach()) >= 0)
                     if self.freedom == "process" else (
                         actual[pair].latency if pair in actual else 0
                     ))
            if present and set(pair) <= active:
                edges.append(ConnectionSpec(pair[0], "out", pair[1], "in", ChannelKind.SIGNAL,
                                            latency=delay))
                decisions["edges"].append({"source": pair[0], "target": pair[1], "delay": delay})
        schedule_index = (int(self.schedule_logits.detach().argmax())
                          if self.freedom == "process" else 0)
        order = [name for name in self.orders[schedule_index] if name in active]
        decisions["schedule"] = order
        projected = replace(
            self.system, mechanisms=tuple(nodes), connections=tuple(edges),
            schedules=tuple(ScheduleSpec(name, index) for index, name in enumerate(order)),
        )
        validate_generative_system(projected)
        return projected, decisions


def rollout(
    design: RelaxedProgramSystem, world: Mapping[str, Any], *, periods: int = 3,
    hard: bool = False, record: bool = False,
) -> dict[str, Any]:
    """Unroll mechanism messages, internal states and world transitions.

    Zero-delay messages see this period's output if the source already ran;
    otherwise they see the prior period. One-period messages always see the
    prior period. Schedule relaxation mixes full within-period executions,
    then mixes state at the boundary. This is an explicit approximation.
    """
    validate_world(world)
    if isinstance(periods, bool) or not isinstance(periods, int) or not 1 <= periods <= 8:
        raise ValueError("miniature periods must be in [1,8]")
    if hard:
        projected, decisions = design.project()
        exact = RelaxedProgramSystem(projected, alternatives=1, freedom="parameters")
        return _rollout(exact, world, periods=periods, hard=True, record=record,
                        decisions=decisions)
    return _rollout(design, world, periods=periods, hard=False, record=record)


def _rollout(
    design: RelaxedProgramSystem, world: Mapping[str, Any], *, periods: int,
    hard: bool, record: bool, decisions: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    size = world["population"]
    values = {name: torch.tensor(world[name], dtype=DTYPE)
              for name in ("quality", "novelty", "resources", "knowledge")}
    zero = torch.zeros(size, dtype=DTYPE)
    previous = {name: zero for name in design.names}
    states = {(name, choice): {key: torch.full((size,), value, dtype=DTYPE)
                              for key, value in program["state"].items()}
              for name in design.names for choice, program in enumerate(design.bank[name])}
    actual = {(edge.source_mechanism, edge.target_mechanism): edge
              for edge in design.system.connections}
    fixed_graph = hard or design.freedom in {"parameters", "rules"}
    node_gates = {name: torch.tensor(1.0, dtype=DTYPE) if fixed_graph
                  else design.node_logits[name].sigmoid() for name in design.names}
    edge_gates = {pair: torch.tensor(float(pair in actual), dtype=DTYPE) if fixed_graph
                  else design.edge_logits[key].sigmoid()
                  for pair, key in design.edge_keys.items()}
    delays = {pair: design.delay_logits[key].sigmoid() if (
        not hard and design.freedom == "process"
    ) else torch.tensor(float(actual[pair].latency if pair in actual else 0), dtype=DTYPE)
              for pair, key in design.edge_keys.items()}
    schedule_weights = (design.schedule_logits.softmax(0) if not hard and design.freedom == "process"
                        else torch.tensor([1.0] + [0.0] * (len(design.orders) - 1), dtype=DTYPE))
    total_production = torch.zeros((), dtype=DTYPE)
    total_burden = torch.zeros((), dtype=DTYPE)
    history: list[dict[str, Any]] = []
    for period in range(periods):
        branches = []
        for order in design.orders:
            current: dict[str, torch.Tensor] = {}
            next_states = {}
            signals = {}
            for name in order:
                signal = zero
                for source in design.names:
                    if source == name:
                        continue
                    pair = (source, name)
                    timely = current.get(source, previous[source])
                    signal = signal + edge_gates[pair] * (
                        (1 - delays[pair]) * timely + delays[pair] * previous[source]
                    )
                signals[name] = signal
                rule_weights = (design.rule_logits[name].softmax(0) if not hard and
                                design.freedom != "parameters" else torch.tensor(
                                    [1.0] + [0.0] * (len(design.bank[name]) - 1), dtype=DTYPE,
                                ))
                output = zero
                for choice, program in enumerate(design.bank[name]):
                    emitted, updated = execute_program(
                        program, {**values, "signal": signal}, size=size,
                        state=states[name, choice],
                        parameters=None if hard else design.parameter_values(name, choice),
                        hard=hard,
                    )
                    output = output + rule_weights[choice] * emitted
                    next_states[name, choice] = {
                        key: node_gates[name] * value + (1 - node_gates[name]) * states[name, choice][key]
                        for key, value in updated.items()
                    }
                current[name] = node_gates[name] * output
            branches.append((current, next_states, signals))
        current = {name: sum(weight * branch[0][name] for weight, branch in zip(
            schedule_weights, branches, strict=True,
        )) for name in design.names}
        states = {key: {field: sum(weight * branch[1][key][field] for weight, branch in zip(
            schedule_weights, branches, strict=True,
        )) for field in state} for key, state in states.items()}
        effects = {kind: zero for kind in EFFECTS}
        for node in design.system.mechanisms:
            for kind, strength in node.parameters["effects"].items():
                effects[kind] = effects[kind] + strength * current[node.mechanism_id]
        # These are the declared miniature-world laws. All institutions affect
        # the world only through explicit numeric effects and message edges.
        allocation = torch.softmax(effects["allocation"], dim=0) * size
        resources = 0.65 * values["resources"] + 0.35 * allocation
        effort = torch.sigmoid(effects["effort"])
        access = torch.sigmoid(effects["access"])
        production = values["quality"] * torch.sigmoid(resources) * effort * access
        knowledge = 0.85 * values["knowledge"] + production * torch.sigmoid(effects["learning"])
        quality = torch.sigmoid(torch.logit(values["quality"].clamp(1e-8, 1 - 1e-8))
                                + 0.3 * knowledge + 0.1 * effects["learning"])
        total_production = total_production + production.mean()
        total_burden = total_burden + sum(value.square().mean() for value in current.values())
        values = {**values, "resources": resources, "knowledge": knowledge, "quality": quality}
        previous = current
        if record:
            history.append({
                "period": period,
                "world": {name: value.detach().tolist() for name, value in values.items()},
                "mechanisms": {name: value.detach().tolist() for name, value in current.items()},
                "signals": {name: sum(weight * branch[2][name] for weight, branch in zip(
                    schedule_weights, branches, strict=True,
                )).detach().tolist() for name in design.names},
                "execution_order": list(design.orders[0]) if hard else None,
                "production": production.detach().tolist(),
                "allocation": allocation.detach().tolist(),
            })
    metrics = {
        "production": total_production / periods,
        "knowledge": values["knowledge"].mean(),
        "novelty": (values["knowledge"] * values["novelty"]).mean(),
        "resource_dispersion": values["resources"].std(unbiased=False),
        "burden": total_burden / periods,
    }
    if any(not torch.isfinite(value) for value in metrics.values()):
        raise ValueError("world produced non-finite metrics")
    return {"metrics": metrics, "history": history, "projection": decisions,
            "world_sha256": digest(world)}


def tensor_loss(metrics: Mapping[str, torch.Tensor], loss_spec: Mapping[str, Any]) -> torch.Tensor:
    validate_loss_spec(loss_spec)
    value = torch.tensor(loss_spec["per_run"]["intercept"], dtype=DTYPE)
    for term in loss_spec["per_run"]["terms"]:
        if term["slice_id"] is not None or term["metric_id"] not in metrics:
            raise ValueError("LossSpec input unavailable in numeric world")
        value = value + term["coefficient"] * metrics[term["metric_id"]]
    return value


def make_world_loss(metric: str) -> dict[str, Any]:
    if metric not in METRICS:
        raise ValueError("unknown miniature metric")
    return {
        "schema": "scienceutopia.loss-spec.v1", "id": f"program-world-{metric}-v1",
        "version": "1.0.0", "status": "miniature-development",
        "optimization_seed_role": "development", "direction": "minimize",
        "per_run": {"intercept": 0.0, "terms": [{
            "metric_id": metric, "slice_id": None,
            "coefficient": 1.0 if metric in {"burden", "resource_dispersion"} else -1.0,
        }]},
        "across_seeds": {"aggregation": "mean_plus_population_sd",
                         "dispersion_weight": 0.0, "minimum_valid_runs": 1},
    }


def aggregate_tensor_loss(
    losses: list[torch.Tensor], loss_spec: Mapping[str, Any],
) -> torch.Tensor:
    if len(losses) < loss_spec["across_seeds"]["minimum_valid_runs"]:
        raise ValueError("insufficient development worlds")
    stacked = torch.stack(losses)
    weight = loss_spec["across_seeds"]["dispersion_weight"]
    return stacked.mean() + weight * stacked.std(unbiased=False) if weight else stacked.mean()


def evaluate_program_system(
    system: SystemSpec, worlds: list[Mapping[str, Any]], loss_spec: Mapping[str, Any],
    *, periods: int = 3, record: bool = False,
) -> dict[str, Any]:
    """Opaque, discrete outer boundary for generated science systems."""
    validate_generative_system(system)
    design = RelaxedProgramSystem(system, alternatives=1, freedom="parameters")
    runs = []
    losses = []
    with torch.no_grad():
        for world in worlds:
            validate_world(world)
            if isinstance(periods, bool) or not isinstance(periods, int) or not 1 <= periods <= 8:
                raise ValueError("miniature periods must be in [1,8]")
            result = _rollout(design, world, periods=periods, hard=True, record=record)
            losses.append(tensor_loss(result["metrics"], loss_spec))
            runs.append({
                "world_sha256": result["world_sha256"],
                "metrics": {key: float(value) for key, value in result["metrics"].items()},
                "history": result["history"],
            })
    return {
        "status": "complete", "system_fingerprint": system.fingerprint,
        "loss_spec_sha256": loss_spec_sha256(loss_spec),
        "loss": float(aggregate_tensor_loss(losses, loss_spec)), "runs": runs,
        "backend": "discrete-numeric-program-world-v1",
    }
